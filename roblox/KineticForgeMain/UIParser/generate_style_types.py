# Regenerates StyleTypes.luau from luau-lsp's Roblox definitions, e.g. after a Roblox update:
#   python roblox/KineticForgeMain/UIParser/generate_style_types.py "%APPDATA%/Code/User/globalStorage/johnnymorganz.luau-lsp/globalTypes.PluginSecurity.d.luau" roblox/KineticForgeMain/UIParser/StyleTypes.luau
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
out_path = sys.argv[2]

ALIASES = dict(re.findall(r"^type (\w+) = (\w+)$", src, re.M))

classes = {}
for m in re.finditer(r"^declare extern type (\w+) extends (\w+) with\n(.*?)^end", src, re.S | re.M):
    name, parent, body = m.groups()
    props = {}
    for line in body.splitlines():
        pm = re.match(r"^\t(\w+): (.+)$", line)
        if not pm:
            continue
        prop, typ = pm.groups()
        if "function" in typ or "RBXScriptSignal" in typ or "(" in typ:
            continue
        props[prop] = typ
    classes[name] = (parent, props)

# Read-only or not meaningful to style
SKIP = re.compile(r"^(Absolute|TextBounds$|TextFits$|ContentText$|IsLoaded$|GuiState$|Archivable$|ClassName$|Parent$|Name$|RobloxLocked$|UniqueId$|Capabilities$|Sandboxed$|SelectionGroup$|NextSelection|SelectionBehavior|RootLocalizationTable$|Localize$|AutoLocalize$|SelectionImageObject$|ClipsDescendants$|SelectionOrder$)")

def collect(name):
    props = {}
    while name in classes and name not in ("Instance", "GuiBase", "UIBase"):
        parent, own = classes[name]
        for k, v in own.items():
            props.setdefault(k, v)
        name = parent
    return {k: v for k, v in props.items() if not SKIP.match(k)}

gui = {}
for cls in ["Frame", "TextLabel", "TextButton", "TextBox", "ScrollingFrame", "ImageLabel", "ImageButton", "CanvasGroup"]:
    for k, v in collect(cls).items():
        if k in gui and v not in gui[k].split(" | "):
            gui[k] = gui[k] + " | " + v
        else:
            gui.setdefault(k, v)

components = ["UIPadding", "UICorner", "UIStroke", "UIListLayout", "UIGridLayout", "UIFlexItem", "UISizeConstraint",
              "UITextSizeConstraint", "UIAspectRatioConstraint", "UIGradient", "UIScale"]

def field(k, v):
    v = v if v.endswith("?") is False else v[:-1]
    # The Roblox definitions name enums EnumFillDirection internally. Other files can only
    # see the public Enum.FillDirection form.
    v = re.sub(r"\bEnum(?!Item\b)(\w+)", r"Enum.\1", v)
    # Aliases such as ContentId are private to the Roblox definitions too, so inline them
    v = re.sub(r"\b\w+\b", lambda m: ALIASES.get(m.group(0), m.group(0)), v)
    return f"\t{k}: ({v} | StyleToken)?,"

lines = [
    "--!strict",
    "-- Types for the style rule tables passed to SetRule in Markup/Styles.luau.",
    "-- Generated by generate_style_types.py from luau-lsp's Roblox definitions, so it only",
    "-- lists properties that exist. Edit the script and regenerate rather than editing this.",
    "-- Every value can also be a token string such as \"$Padding\".",
    "",
    "export type StyleToken = string",
    "",
]
for c in components:
    lines.append(f"export type {c}Style = {{")
    for k, v in sorted(collect(c).items()):
        lines.append(field(k, v))
    lines.append("}")
    lines.append("")

lines.append("export type StyleProps = {")
lines.append("\t-- Default transition for every property in the rule")
lines.append("\tTransition: TweenInfo?,")
lines.append("")
lines.append("\t-- Pseudo-instances the rule creates inside matching elements")
for c in components:
    lines.append(f'\t["::{c}"]: {c}Style?,')
lines.append("")
for k, v in sorted(gui.items()):
    lines.append(field(k, v))
lines.append("")
lines.append("\t-- Nested selectors, such as \":Hover\"")
lines.append("\t[string]: StyleProps,")
lines.append("}")
lines.append("")
lines.append("-- Only the types are used, but a ModuleScript has to return a value")
lines.append("return {}")
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(len(gui), "gui properties;", sum(len(collect(c)) for c in components), "component properties")
